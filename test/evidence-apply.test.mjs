import assert from 'node:assert/strict';
import { test } from 'node:test';
import { applyEvidenceOverlay, parseEvidenceOverlay } from '../lib/evidence-apply.mjs';

const model = (extra = {}) => ({ id: 'test-model', efforts: ['low', 'high'], capability: {}, ...extra });
const config = (models) => ({ provider: 'anthropic', models });
const overlay = (entries) => ({
  checked: '2026-11-22',
  source: 'https://artificialanalysis.ai/',
  tier: 'free',
  entries,
});
const entry = (aliases, capability) => ({
  aliases,
  capability,
  scores: {},
  confidence: {},
  sources: ['artificial_analysis'],
});

test('an overlay seeds a model matched by a canonical id or alias', () => {
  const seeded = { low: { default: 1, code: 1.5 }, high: { default: 2, code: 2.5 } };
  for (const [configuredId, key, aliases] of [
    ['glm-5.3[1m]', 'glm-5.3', ['zai-org/GLM-5.3']],
    ['zai-org/GLM-5.3[1m]', 'glm-5.3', ['zai-org/GLM-5.3']],
    ['glm-5.3[1m]', 'zai-glm-5.3', ['glm-5.3[1m]']],
  ]) {
    const result = applyEvidenceOverlay(
      config({ glm: model({ id: configuredId }) }),
      overlay({ [key]: entry(aliases, seeded) }),
    );
    assert.deepEqual(result.models.glm.capability, seeded, `${key} / ${configuredId}`);
  }
});

test('a user-declared capability map wins in full and other models still seed', () => {
  const declared = { low: 0.5 };
  const result = applyEvidenceOverlay(
    config({ glm: model({ capability: { ...declared } }), opus: model({ id: 'opus' }) }),
    overlay({
      'glm-5.3': entry(['test-model'], { high: { default: 3 } }),
      opus: entry(['opus'], { high: { default: 2 } }),
    }),
    { models: { glm: { capability: declared } } },
  );
  assert.deepEqual(result.models.glm.capability, declared);
  assert.deepEqual(result.models.opus.capability, { high: { default: 2 } });
});

test('only the efforts a configured model supports are seeded, and preset seeds stay', () => {
  const result = applyEvidenceOverlay(
    config({ glm: model({ efforts: ['medium', 'high'], capability: { medium: 1 } }) }),
    overlay({ 'glm-5.3': entry(['test-model'], { low: { default: 1 }, high: { default: 2 } }) }),
  );
  assert.deepEqual(result.models.glm.capability, { medium: 1, high: { default: 2 } });
});

test('a model with no efforts takes the default capability column', () => {
  const result = applyEvidenceOverlay(
    config({ flash: model({ efforts: [], capability: {} }) }),
    overlay({ flash: entry(['test-model'], { default: { default: 2, ops: 2.5 }, high: { default: 3 } }) }),
  );
  assert.deepEqual(result.models.flash.capability, { default: { default: 2, ops: 2.5 } });
});

test('a malformed overlay or entry is ignored and never throws', () => {
  const base = config({ glm: model({ id: 'glm-5.3' }) });
  const before = structuredClone(base);
  for (const bad of [
    null,
    undefined,
    'text',
    [],
    {},
    { entries: null },
    { entries: [] },
    { entries: { glm: null } },
    { entries: { glm: { aliases: 'not-a-list', capability: { high: { default: '2' } } } } },
    { entries: { glm: { aliases: ['glm-5.3'], capability: 'bad' } } },
    { entries: { glm: { aliases: ['glm-5.3'], capability: { high: [] } } } },
  ]) {
    const result = applyEvidenceOverlay(base, bad);
    assert.deepEqual(result, before);
  }
  assert.deepEqual(base, before);
});

test('valid cells survive beside invalid ones in a malformed capability row', () => {
  const result = applyEvidenceOverlay(
    config({ glm: model({ id: 'glm-5.3' }) }),
    overlay({
      glm: entry(['glm-5.3'], {
        low: 'text',
        high: { default: '2', code: -1, debug: 4, ops: 2.5, plan: 0.25, junk: 1 },
      }),
    }),
  );
  assert.deepEqual(result.models.glm.capability, { high: { ops: 2.5 } });
});

test('applying an overlay returns a new config and never mutates the input', () => {
  const base = config({ glm: model({ id: 'glm-5.3' }) });
  const before = structuredClone(base);
  const result = applyEvidenceOverlay(base, overlay({ glm: entry(['glm-5.3'], { high: { default: 2 } }) }));
  assert.notEqual(result, base);
  assert.notEqual(result.models, base.models);
  assert.deepEqual(base, before);
});

test('the generated module text parses without importing it', () => {
  const value = overlay({ glm: entry(['glm-5.3'], { high: { default: 2 } }) });
  const text = [
    '// Generated by scripts/aa-evidence.mjs from the Artificial Analysis free API.',
    `export const EVIDENCE_LOCAL = ${JSON.stringify(value, null, 2)};`,
    '',
  ].join('\n');
  assert.deepEqual(parseEvidenceOverlay(text), value);
  for (const bad of [null, undefined, 42, '', 'export const OTHER = {};', 'export const EVIDENCE_LOCAL = {'])
    assert.equal(parseEvidenceOverlay(bad), null, String(bad));
});
