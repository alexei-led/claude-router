// Writes lib/probe-results.mjs, the last checked-in activity probe per classifier, from
// experiments/mod-router/results/activity-probe-*.json. The pane reads the module because experiments/ is not shipped.
// scripts/probe-activity.mjs runs this after each probe; test/probe-results.test.mjs fails when the module and the
// result files disagree.
// Usage: node scripts/probe-results.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const RESULTS = new URL('../experiments/mod-router/results/', import.meta.url);
const MODULE = new URL('../lib/probe-results.mjs', import.meta.url);
const NAME = /^activity-probe-(.+)\.json$/;

// Every probe result file, parsed, in classifier order.
export function readProbeResults(dir = RESULTS) {
  return readdirSync(dir)
    .filter((file) => NAME.test(file))
    .sort()
    .map((file) => JSON.parse(readFileSync(new URL(file, dir), 'utf8')));
}

// A run that got no answer, or no latency to report, says nothing about the classifier: a revoked key or a dead
// network. It must not replace a good result.
export const isUsableProbe = (r) => r.answered > 0 && Number.isFinite(r.latencyMs?.p95);

// The module text for `results`: per classifier the model probed, correct answers, probes, p95 latency in ms and the
// UTC date of the run. JSON keeps any id or model text a valid literal; Biome skips the file, so the text stays what
// this writes.
export function probeModule(results) {
  const rows = results.map((r) => {
    if (!isUsableProbe(r)) throw new Error(`${r.classifier}: the probe run has no answer or no p95 latency`);
    const correct = Math.round(r.accuracy * r.probes);
    const date = r.date.slice(0, 10);
    return [r.classifier, { model: r.model, correct, probes: r.probes, p95Ms: r.latencyMs.p95, date }];
  });
  return [
    '// Generated by scripts/probe-results.mjs from experiments/mod-router/results/activity-probe-*.json; do not edit.',
    '// The last checked-in activity probe per classifier id: the model it probed, correct answers of the probes, p95',
    '// latency in ms, and the UTC date of the run.',
    `export const PROBE_RESULTS = ${JSON.stringify(Object.fromEntries(rows), null, 2)};`,
    '',
  ].join('\n');
}

export function writeProbeModule() {
  writeFileSync(MODULE, probeModule(readProbeResults()));
  return fileURLToPath(MODULE);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(`wrote ${writeProbeModule()}`);
